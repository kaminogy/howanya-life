package com.kamino.howanyalife.ui

import android.content.Context
import android.media.AudioAttributes
import android.media.AudioManager
import android.media.MediaPlayer
import android.media.SoundPool
import androidx.annotation.RawRes
import androidx.compose.runtime.Composable
import androidx.compose.runtime.DisposableEffect
import androidx.compose.runtime.LaunchedEffect
import androidx.compose.runtime.remember
import androidx.compose.ui.platform.LocalContext
import androidx.lifecycle.compose.LifecycleResumeEffect
import com.kamino.howanyalife.data.SoundMode
import com.kamino.howanyalife.data.SoundSettings
import com.kamino.howanyalife.model.CatAction
import com.kamino.howanyalife.shared.R

/** Short sounds, generated by tools/HowanyaSounds.py. */
enum class Sfx(@param:RawRes val res: Int, val volume: Float) {
    FEED(R.raw.sfx_feed, 0.8f),
    EAT(R.raw.sfx_eat, 0.9f),
    LAUGH(R.raw.sfx_laugh, 0.9f),
    CRY(R.raw.sfx_cry, 0.8f),
    PET(R.raw.sfx_pet, 0.7f),
    STRETCH(R.raw.sfx_stretch, 0.8f),
}

/** Plays sound effects through a SoundPool and the looping background music through a MediaPlayer. */
class SoundPlayer(private val context: Context) {

    private val attributes = AudioAttributes.Builder()
        .setUsage(AudioAttributes.USAGE_GAME)
        .setContentType(AudioAttributes.CONTENT_TYPE_MUSIC)
        .build()
    private val soundPool = SoundPool.Builder().setMaxStreams(3).setAudioAttributes(attributes).build()
    private val soundIds = Sfx.entries.associateWith { soundPool.load(context, it.res, 1) }
    private val audioManager = context.getSystemService(AudioManager::class.java)

    private var bgm: MediaPlayer? = null
    @RawRes private var bgmRes = 0

    fun play(sfx: Sfx) {
        soundIds[sfx]?.let { soundPool.play(it, sfx.volume, sfx.volume, 1, 0, 1f) }
    }

    fun playBgm(@RawRes res: Int) {
        if (res == bgmRes && bgm?.isPlaying == true) return
        stopBgm()
        // Don't talk over music or a podcast the user is already listening to.
        if (audioManager.isMusicActive) return
        bgm = MediaPlayer.create(context, res, attributes, audioManager.generateAudioSessionId())?.apply {
            isLooping = true
            setVolume(BGM_VOLUME, BGM_VOLUME)
            start()
        }
        bgmRes = res
    }

    fun stopBgm() {
        bgm?.release()
        bgm = null
        bgmRes = 0
    }

    fun release() {
        stopBgm()
        soundPool.release()
    }

    private companion object {
        const val BGM_VOLUME = 0.35f
    }
}

/** The saved sound setting for this app; [default] applies until the user changes it. */
@Composable
fun rememberSoundSettings(default: SoundMode): SoundSettings {
    val context = LocalContext.current
    return remember { SoundSettings(context.applicationContext, default) }
}

/** Icon for the sound button, which cycles through the modes. */
val SoundMode.icon: String
    get() = when (this) {
        SoundMode.ALL -> "🎵"
        SoundMode.EFFECTS_ONLY -> "🔔"
        SoundMode.OFF -> "🔇"
    }

/**
 * Adds sound to a cat screen: day or night background music while the screen is visible,
 * and a sound effect for the bowl coming out, eating, laughing, crying, being petted and stretching.
 */
@Composable
fun CatSounds(ui: CatUiState, mode: SoundMode?, petted: Int) {
    val context = LocalContext.current
    val player = remember { SoundPlayer(context.applicationContext) }
    DisposableEffect(player) { onDispose { player.release() } }

    LifecycleResumeEffect(player, mode, ui.night) {
        if (mode == SoundMode.ALL) {
            player.playBgm(if (ui.night) R.raw.bgm_night else R.raw.bgm_day)
        } else {
            player.stopBgm()
        }
        onPauseOrDispose { player.stopBgm() }
    }

    // Stay silent until the saved setting has loaded (mode == null).
    val effectsOn = mode == SoundMode.ALL || mode == SoundMode.EFFECTS_ONLY
    LaunchedEffect(ui.action) {
        if (!effectsOn) return@LaunchedEffect
        when (ui.action) {
            CatAction.EAT -> player.play(Sfx.EAT)
            CatAction.LAUGH -> player.play(Sfx.LAUGH)
            CatAction.CRY -> player.play(Sfx.CRY)
            CatAction.STRETCH -> player.play(Sfx.STRETCH)
            else -> Unit
        }
    }
    LaunchedEffect(ui.bowlX != null) {
        if (effectsOn && ui.bowlX != null) player.play(Sfx.FEED)
    }
    LaunchedEffect(petted) {
        if (effectsOn && petted > 0) player.play(Sfx.PET)
    }
}
